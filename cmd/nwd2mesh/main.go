// nwd2mesh exports geometry from a Navisworks .nwd file through go-topo
// (OpenCASCADE).
//
// Usage:
//
//	nwd2mesh <file.nwd> <out.ply|out.step|out.stl>
//
// Output fidelity (go-nwd findings):
//   - .ply   point cloud of every decoded vertex (always exact);
//   - .step  wireframe + faces: line sets (exact segments) and the
//            unambiguous small polygons (3-vertex triangles, 4-vertex
//            quads); larger triangle-set elements emit vertices only;
//   - .stl   triangulated faces only (small polygons); a line-only model
//            yields an empty STL because STL has no edges.
//
// Filled surfaces of the large triangle-set elements require the
// quantized index table that go-nwd does not yet locate (U21), so they are
// deliberately not emitted as (wrong) triangle soup.
package main

import (
	"bufio"
	"encoding/binary"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"strings"

	topo "github.com/flywave/go-topo"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: nwd2mesh <file.nwd> <out.ply|out.step|out.stl>")
		os.Exit(2)
	}
	in, out := os.Args[1], os.Args[2]
	r := topo.NewNwdReader()
	if err := r.Load(in); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
	els := r.GetElements()

	switch strings.ToLower(filepath.Ext(out)) {
	case ".ply":
		n, err := writePLY(out, els)
		if err != nil {
			fmt.Fprintln(os.Stderr, "PLY export:", err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "wrote %s: %d vertices (%d elements)\n", out, n, len(els))
		return
	}

	var shapes []topo.Shape
	shaped := 0
	for _, e := range els {
		if e.Shape != nil {
			shapes = append(shapes, *e.Shape)
			shaped++
		}
	}
	if len(shapes) == 0 {
		fmt.Fprintln(os.Stderr, "no bridged shapes (line sets / small polygons)")
		os.Exit(1)
	}
	comp := topo.TopoCompoundMake(shapes)
	sh := comp.ToShape()

	switch strings.ToLower(filepath.Ext(out)) {
	case ".stl":
		n, err := writeSTL(out, sh)
		if err != nil {
			fmt.Fprintln(os.Stderr, "STL export:", err)
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "wrote %s: %d triangles from %d/%d elements\n", out, n, shaped, len(els))
	case ".step", ".stp":
		if !sh.ExportStepUnit(out, true, 0, "MM") {
			fmt.Fprintln(os.Stderr, "STEP export failed")
			os.Exit(1)
		}
		fmt.Fprintf(os.Stderr, "wrote %s from %d/%d elements\n", out, shaped, len(els))
	default:
		fmt.Fprintln(os.Stderr, "unsupported output extension (use .ply, .step or .stl)")
		os.Exit(2)
	}
}

// writePLY writes the decoded vertices as an ASCII PLY point cloud.
func writePLY(path string, els []*topo.NwdElement) (int, error) {
	total := 0
	for _, e := range els {
		total += len(e.Vertices)
	}
	f, err := os.Create(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()
	w := bufio.NewWriter(f)
	defer w.Flush()
	fmt.Fprintln(w, "ply")
	fmt.Fprintln(w, "format ascii 1.0")
	fmt.Fprintln(w, "comment generated by go-nwd + go-topo")
	fmt.Fprintf(w, "element vertex %d\n", total)
	fmt.Fprintln(w, "property float x")
	fmt.Fprintln(w, "property float y")
	fmt.Fprintln(w, "property float z")
	fmt.Fprintln(w, "end_header")
	for _, e := range els {
		for _, v := range e.Vertices {
			fmt.Fprintf(w, "%.6f %.6f %.6f\n", v[0], v[1], v[2])
		}
	}
	return total, nil
}

// writeSTL triangulates the shape via go-topo's mesh receiver and writes a
// binary STL.
func writeSTL(path string, sh *topo.Shape) (int, error) {
	m := topo.NewMeshReceiver()
	sh.Mesh(m, 0.5, 0.5, 0.5)

	f, err := os.Create(path)
	if err != nil {
		return 0, err
	}
	defer f.Close()

	count := 0
	for fi := range m.Tris {
		count += len(m.Tris[fi])
	}
	var hdr [80]byte
	copy(hdr[:], "go-nwd nwd2mesh binary STL")
	if _, err := f.Write(hdr[:]); err != nil {
		return 0, err
	}
	var cnt [4]byte
	binary.LittleEndian.PutUint32(cnt[:], uint32(count))
	if _, err := f.Write(cnt[:]); err != nil {
		return 0, err
	}
	written := 0
	for fi := range m.Tris {
		vers := m.Vers[fi]
		for _, t := range m.Tris[fi] {
			if t[0] < 0 || t[0] >= len(vers) || t[1] < 0 || t[1] >= len(vers) || t[2] < 0 || t[2] >= len(vers) {
				continue
			}
			p0, p1, p2 := vers[t[0]], vers[t[1]], vers[t[2]]
			n := normal(p0, p1, p2)
			var rec [50]byte
			putVec(rec[0:12], n)
			putVec(rec[12:24], f32vec(p0))
			putVec(rec[24:36], f32vec(p1))
			putVec(rec[36:48], f32vec(p2))
			if _, err := f.Write(rec[:]); err != nil {
				return written, err
			}
			written++
		}
	}
	return written, nil
}

func normal(p0, p1, p2 topo.Point3) [3]float32 {
	a := p0.Data()
	b := p1.Data()
	c := p2.Data()
	u := [3]float64{b[0] - a[0], b[1] - a[1], b[2] - a[2]}
	v := [3]float64{c[0] - a[0], c[1] - a[1], c[2] - a[2]}
	n := [3]float64{u[1]*v[2] - u[2]*v[1], u[2]*v[0] - u[0]*v[2], u[0]*v[1] - u[1]*v[0]}
	l := math.Sqrt(n[0]*n[0] + n[1]*n[1] + n[2]*n[2])
	if l == 0 {
		return [3]float32{0, 0, 0}
	}
	return [3]float32{float32(n[0] / l), float32(n[1] / l), float32(n[2] / l)}
}

func f32vec(p topo.Point3) [3]float32 {
	d := p.Data()
	return [3]float32{float32(d[0]), float32(d[1]), float32(d[2])}
}

func putVec(dst []byte, v [3]float32) {
	binary.LittleEndian.PutUint32(dst[0:4], math.Float32bits(v[0]))
	binary.LittleEndian.PutUint32(dst[4:8], math.Float32bits(v[1]))
	binary.LittleEndian.PutUint32(dst[8:12], math.Float32bits(v[2]))
}
